/**
 * Regenerate the frozen reference distribution.
 *
 *   npx tsx scripts/reference.ts <path-to-analysis.csv>
 *
 * Why this exists
 * ---------------
 * Tag cutoffs used to be percentiles of whatever library was in front of the
 * tagger. That makes a label mean "dark relative to these tracks", so adding
 * records silently re-tags the ones already there, and filtering to a playlist
 * re-bases every threshold against a handful of songs.
 *
 * It also doesn't survive its own logic: grow the library toward everything
 * ever released and percentile-of-your-library converges on
 * percentile-of-all-music — a fixed cutoff. Library-relative percentiles were
 * only ever a small-sample stand-in for a global one, so the real question is
 * which population you measure against, not whether to measure at all.
 *
 * So the cutoffs are computed once here, over the full analysis corpus, and
 * committed as data. A record then tags the same way everywhere.
 *
 * The CSV is a private music library and is not part of this repo. The
 * generated `lib/library/reference.ts` is, and is all the app needs.
 *
 * Expected columns: artist, title, normalized_genre_tags,
 * normalized_vibe_tags, bpm, danceability_score.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { computeThresholds } from "../lib/library/tagger";
import { reconstructMoodGenre } from "../lib/library/build-catalog";
import type { Track } from "../lib/library/types";

const csvPath = process.argv[2];
if (!csvPath) {
  console.error("usage: npx tsx scripts/reference.ts <path-to-analysis.csv>");
  process.exit(1);
}

/** Minimal RFC-4180 reader: quoted fields, doubled quotes, embedded commas. */
function parseCsv(text: string): Record<string, string>[] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;

  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else quoted = false;
      } else field += c;
      continue;
    }
    if (c === '"') quoted = true;
    else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (c !== "\r") field += c;
  }
  if (field || row.length) {
    row.push(field);
    rows.push(row);
  }

  const [header, ...body] = rows;
  return body
    .filter((r) => r.length === header.length)
    .map((r) => Object.fromEntries(header.map((h, i) => [h, r[i]])));
}

const list = (s: string) =>
  (s ?? "")
    .split(",")
    .map((x) => x.trim())
    .filter(Boolean);

const records = parseCsv(readFileSync(csvPath, "utf8"));

const tracks: Track[] = [];
for (const r of records) {
  const bpm = Number(r.bpm);
  const danceability = Number(r.danceability_score);
  if (!Number.isFinite(bpm) || !Number.isFinite(danceability)) continue;

  const { genre, mood } = reconstructMoodGenre({
    artist: r.artist ?? "",
    title: r.title ?? "",
    genre: list(r.normalized_genre_tags),
    vibe: list(r.normalized_vibe_tags),
  });

  // Only bpm, danceability, genre and mood feed computeThresholds; the rest of
  // Features is filled with inert values so the shape typechecks.
  tracks.push({
    id: `r${tracks.length}`,
    artist: r.artist ?? "",
    title: r.title ?? "",
    features: {
      bpm,
      key: "1A",
      durationS: 0,
      danceability,
      vocal: r.vocal_instrumental === "voice" ? 0.82 : 0.14,
      genre,
      mood,
      intro: "short",
      outro: "clean",
      familiarity: "known",
      vocalDetail: "none",
      rhythm: "four-on-the-floor",
      hasBreakdown: true,
    },
  });
}

if (tracks.length < 100) {
  console.error(`only ${tracks.length} usable rows — refusing to freeze a reference that thin`);
  process.exit(1);
}

const th = computeThresholds(tracks);

const out = `/**
 * Frozen tag cutoffs.
 *
 * Generated by \`scripts/reference.ts\` over a ${tracks.length}-track analysis corpus.
 * Do not hand-edit — regenerate instead.
 *
 * These are the bars a track's measured values are compared against. They are
 * fixed on purpose: a record should tag the same way whoever owns it and
 * whatever else is sitting next to it on disk. The tagger can still compute
 * cutoffs from a specific library on request — see \`tagLibrary\` — but that is
 * a second view, not the default.
 */

import type { Thresholds } from "./tagger";

/** Number of tracks the distribution below was measured over. */
export const REFERENCE_CORPUS_SIZE = ${tracks.length};

export const REFERENCE_THRESHOLDS: Thresholds = ${JSON.stringify(th, null, 2)};
`;

const dest = join(process.cwd(), "lib", "library", "reference.ts");
writeFileSync(dest, out, "utf8");

console.log(`read    ${records.length} rows, used ${tracks.length}`);
console.log(`bpm median ${th.bpmMedian}  danceability p75 ${th.danceP75}`);
console.log("mood p75 cutoffs:");
for (const [k, v] of Object.entries(th.mood)) {
  console.log(`  ${k.padEnd(16)} p33 ${v.p33.toFixed(3)}  p75 ${v.p75.toFixed(3)}  p90 ${v.p90.toFixed(3)}`);
}
console.log(`\nwrote ${dest}`);
